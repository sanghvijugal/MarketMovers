"""Dhanteras reel: one timing list for picture and sound.

Builds every event (coin landings, footsteps, brand coins, bells), writes it into
composition/index.html, and synthesises the soundtrack from the same list:
shehnai (raag Bhupali) over a soft drone, temple bells, a coin clink on every landing,
ghungroo on the footsteps and a dholak pulse on the beat (100 BPM, a beat every 0.6 s).

usage: python make_audio.py            shehnai version  -> composition/
       python make_audio.py chanakya   timed to the "Chanakya" song -> composition-chanakya/
       (needs numpy; the chanakya mode also needs the song at chanakya.wav next to this file)
"""
import json, os, sys, wave
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
MODE = sys.argv[1] if len(sys.argv) > 1 else "shehnai"
COMP = os.path.join(HERE, "composition" if MODE == "shehnai" else "composition-chanakya")
SR, DUR, BEAT = 44100, 12.0, 0.6
N = int(SR * DUR)
rng = np.random.default_rng(11)

# ------------------------------------------------------------------ events
T = {"tap": 0.6, "click": 1.8, "pour": 2.4, "diya": 7.8, "flip0": 8.4, "end": 10.2}
SPOUT = {"x": 547, "y": 829}
BOWL = {"x": 540, "rimY": 1380, "w": 560}
G = 9000.0

pour_beats = [2.4, 3.0, 3.6, 4.2, 4.8, 5.4]
if MODE == "chanakya":
    # the song's drop (68.77 s) lands on the first pour; 140 BPM from there
    BEAT = 60 / 140.0
    g = lambda k: round(2.4 + k * BEAT, 3)
    T = {"tap": 0.6, "click": 1.86, "pour": 2.4, "diya": g(12), "flip0": g(14), "end": g(18)}
    pour_beats = [g(k) for k in range(8)]
coins, n = [], 0
for b in pour_beats:
    small = [(b + 0.1 + k * 0.06, 0.35) for k in range(5)] if MODE == "chanakya" else [(b + 0.12 + k * 0.075, 0.35) for k in range(6)]
    lands = [(b + k * 0.035, 1.0) for k in range(4)] + small
    for t, loud in lands:
        spread = min(70 + n * 4, 235)
        dx = float(rng.uniform(-spread, spread))
        H = min(10 + n * 1.5, 92)
        y = BOWL["rimY"] - H * max(0.0, 1 - (dx / 270) ** 2) - 6
        coins.append({"t": round(t, 3), "x": round(BOWL["x"] + dx, 1), "y": round(y, 1), "r": int(rng.integers(26, 35)),
                      "rot": int(rng.integers(-25, 25)), "spin": round(float(rng.uniform(12, 20)), 2), "loud": loud})
        n += 1

steps = [{"t": 6.0, "x": 480, "y": 1835, "side": "L"}, {"t": 6.6, "x": 600, "y": 1740, "side": "R"}, {"t": 7.2, "x": 480, "y": 1645, "side": "L"}]

if MODE == "chanakya":
    for s_, k in zip(steps, (8, 9, 10)):
        s_["t"] = g(k)

NAMES = ["FINOLEX", "ASTRAL", "DUTRON", "SINTEX", "TEXMO", "VECTUS", "WATERFLO", "JOHNSON BATHROOMS", "KISAN", "PLASTO", "MBH", "REWA", "RECO"]
rows = [([120, 330, 540, 750, 960], 640, 8.4), ([225, 435, 645, 855], 860, 9.0), ([225, 435, 645, 855], 1080, 9.6)]
if MODE == "chanakya":
    rows = [(xs, y, g(14 + i)) for i, (xs, y, _) in enumerate(rows)]
brands, i = [], 0
for xs, y, t0 in rows:
    for j, x in enumerate(xs):
        brands.append({"name": NAMES[i], "x": x, "y": y, "t": round(t0 + j * 0.06, 3)})
        i += 1

EV = {"t": T, "spout": SPOUT, "bowl": BOWL, "gravity": G, "coins": coins, "steps": steps, "brands": brands}
tpl = open(os.path.join(HERE, "index.template.html")).read()
if MODE == "chanakya":
    tpl = tpl.replace("assets/audio/dhanteras.wav", "assets/audio/chanakya-clip.wav").replace(
        "shehnai, temple bells and coin jingles, generated by make_audio.py from the same timing list",
        "a 12 s cut of the song Chanakya (66.37 s to 78.37 s), its drop on the first coin")
os.makedirs(COMP, exist_ok=True)
open(os.path.join(COMP, "index.html"), "w").write(tpl.replace("/*EVENTS*/", json.dumps(EV)))
print("events:", len(coins), "coins,", len(steps), "steps,", len(brands), "brand coins; end at", T["end"])
if MODE == "chanakya":
    os.makedirs(os.path.join(COMP, "assets", "audio"), exist_ok=True)
    os.system('ffmpeg -v error -y -ss 66.37 -t 12 -i "' + os.path.join(HERE, "chanakya.wav") + '" -af "afade=t=in:d=0.05,afade=t=out:st=11.4:d=0.6" "'
              + os.path.join(COMP, "assets", "audio", "chanakya-clip.wav") + '"')
    sys.exit(0)

# ------------------------------------------------------------------ synthesis helpers
L = np.zeros(N); R = np.zeros(N)
SA = 392.0  # G4


def put(sig, t, pan=0.5, gain=1.0):
    i0 = int(round(t * SR))
    if i0 >= N:
        return
    j = min(N, i0 + len(sig))
    L[i0:j] += sig[: j - i0] * gain * np.cos(pan * np.pi / 2) * 1.414
    R[i0:j] += sig[: j - i0] * gain * np.sin(pan * np.pi / 2) * 1.414


def partials(freqs, amps, decays, length, attack=0.002):
    tt = np.arange(int(SR * length)) / SR
    s = sum(a * np.sin(2 * np.pi * f * tt + p) * np.exp(-tt / d) for f, a, d, p in zip(freqs, amps, decays, rng.uniform(0, 6, len(freqs))))
    return s * np.minimum(1, tt / attack)




def noise_burst(length, fc_lo, fc_hi, decay):
    tt = np.arange(int(SR * length)) / SR
    nz = rng.standard_normal(len(tt))
    spec = np.fft.rfft(nz); f = np.fft.rfftfreq(len(nz), 1 / SR)
    spec[(f < fc_lo) | (f > fc_hi)] = 0
    return np.fft.irfft(spec, len(nz)) * np.exp(-tt / decay)


def temple_bell(f0, length=5.0, bright=1.0):
    r = [0.5, 1, 1.183, 1.506, 2, 2.514, 2.662, 3.011, 4.166, 5.433]
    a = [0.55, 1, 0.6, 0.5, 0.45, 0.35, 0.3, 0.25, 0.18 * bright, 0.12 * bright]
    d = [5.5, 4.2, 3.4, 2.8, 2.3, 1.9, 1.7, 1.4, 0.9, 0.6]
    s = partials([f0 * x for x in r], a, d, length) + 0.6 * partials([f0 * x * 1.0025 for x in r[:5]], a[:5], d[:5], length)
    s[: int(0.02 * SR)] += noise_burst(0.02, 2000, 9000, 0.004)[: int(0.02 * SR)] * 0.6
    return s / np.max(np.abs(s))


def clink(base, length=0.25):
    return partials([base, base * 2.32, base * 3.81, base * 5.4], [1, 0.6, 0.35, 0.2], [0.09, 0.06, 0.045, 0.03], length, 0.0008)


def coin_land(loud):
    s = clink(rng.uniform(2600, 3600)) * loud
    for k in range(int(rng.integers(1, 3))):  # a little rattle on the pile
        off = int(SR * rng.uniform(0.02, 0.07)); c = clink(rng.uniform(3000, 4200), 0.12) * 0.3 * loud
        s = np.pad(s, (0, max(0, off + len(c) - len(s)))); s[off:off + len(c)] += c
    return s


def ghungroo():
    s = np.zeros(int(SR * 0.4))
    for k in range(7):
        off = int(SR * rng.uniform(0, 0.06)); c = partials([rng.uniform(4200, 7200)], [1], [0.05], 0.2, 0.0005) * 0.5
        s[off:off + len(c)] += c
    return s


def dholak(strong=False):
    tt = np.arange(int(SR * 0.35)) / SR
    f = 70 + 60 * np.exp(-tt * 30)
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-tt * 9)
    slap = noise_burst(0.35, 800, 4000, 0.012)
    return (body + 0.35 * slap) * (1.0 if strong else 0.7)


# ------------------------------------------------------------------ shehnai (raag Bhupali: S R G P D)
RAT = {"P_": 0.75, "D_": 5 / 6, "S": 1, "R": 9 / 8, "G": 5 / 4, "P": 1.5, "D": 5 / 3, "S'": 2}
MEL = [(0.30, 0.30, "D_"), (0.60, 1.15, "S"), (1.80, 0.30, "R"), (2.10, 0.30, "G"), (2.40, 0.60, "P"), (3.00, 0.30, "G"),
       (3.30, 0.30, "P"), (3.60, 0.60, "D"), (4.20, 0.30, "P"), (4.50, 0.30, "G"), (4.80, 0.60, "R"), (5.40, 0.30, "G"),
       (5.70, 0.30, "P"), (6.00, 0.60, "G"), (6.60, 0.60, "P"), (7.20, 0.55, "D"), (7.80, 0.55, "S'"), (8.40, 0.30, "D"),
       (8.70, 0.30, "P"), (9.00, 0.55, "G"), (9.60, 0.30, "R"), (9.90, 0.30, "G"), (10.20, 1.70, "S'")]


def shehnai():
    tt = np.arange(N) / SR
    f = np.zeros(N); amp = np.zeros(N); prev = None
    for ts, d, nm in MEL:
        i0, i1 = int(ts * SR), min(N, int((ts + d) * SR))
        target = SA * RAT[nm]
        seg = np.full(i1 - i0, target)
        if prev is not None:  # meend: glide in from the previous note
            g = min(len(seg), int(0.07 * SR)); seg[:g] = prev * (target / prev) ** (np.arange(g) / g)
        local = np.arange(i1 - i0) / SR
        vib = 1 + 0.006 * np.sin(2 * np.pi * 5.6 * local) * np.clip((local - 0.15) / 0.2, 0, 1)
        f[i0:i1] = seg * vib
        env = np.minimum(1, local / 0.04) * np.clip((d - local) / 0.05, 0.15, 1) * (0.85 + 0.15 * np.clip(local / d, 0, 1))
        if nm == "S'" and ts > 10:
            env *= np.clip((d - local) / 1.2, 0, 1)
        amp[i0:i1] = env; prev = target
    f[f == 0] = SA
    ph = 2 * np.pi * np.cumsum(f) / SR
    out = np.zeros(N)
    for k in range(1, 26):
        fk = f * k
        form = 0.3 + np.exp(-((fk - 1150) / 420) ** 2) + 0.75 * np.exp(-((fk - 2550) / 560) ** 2) + 0.35 * np.exp(-((fk - 3800) / 700) ** 2)
        out += np.where(fk < 9000, form / k ** 0.55, 0) * np.sin(k * ph)
    breath = noise_burst(DUR, 1500, 3500, 1e9)[:N] * 0.03
    return (out / np.max(np.abs(out)) + breath) * amp


def drone():
    tt = np.arange(N) / SR
    s = sum(np.sin(2 * np.pi * SA / 2 * k * tt) / k for k in range(1, 8)) + 0.6 * sum(np.sin(2 * np.pi * SA * 0.75 * k * tt + 1) / k for k in range(1, 6))
    return s * np.clip(tt / 1.0, 0, 1) * np.clip((DUR - tt) / 1.0, 0, 1) * 0.05


# ------------------------------------------------------------------ assemble
mel = shehnai(); put(mel * 0.32, 0, 0.5); put(drone(), 0, 0.5)
put(temple_bell(196, 6), 0.0, 0.5, 0.55)                       # opening bell
put(noise_burst(0.05, 2500, 6000, 0.01) + partials([1500], [0.6], [0.02], 0.05), T["click"], 0.6, 0.5)  # tap handle
for c in coins:
    put(coin_land(c["loud"]), c["t"], 0.15 + 0.7 * c["x"] / 1080, 0.32)
for s in steps:
    put(ghungroo(), s["t"], 0.35 if s["side"] == "L" else 0.65, 0.45)
put(temple_bell(784, 3, 0.8), T["diya"], 0.5, 0.25)            # small bell as the diyas light
for b in brands:
    put(clink(rng.uniform(3400, 4200), 0.3) + 0.5 * clink(rng.uniform(5000, 6000), 0.3), b["t"], 0.15 + 0.7 * b["x"] / 1080, 0.3)
for k in range(int(round((T["end"] - T["pour"]) / BEAT))):     # dholak pulse on every beat while things happen
    t = T["pour"] + k * BEAT
    put(dholak(k % 4 == 0), t, 0.5, 0.35)
put(dholak(True), T["end"], 0.5, 0.5)
put(temple_bell(196, 1.8), T["end"], 0.5, 0.6)                 # closing bell on the end card

# simple stereo reverb for space
def reverb(x, seed):
    r = np.random.default_rng(seed); ln = int(SR * 1.6)
    ir = r.standard_normal(ln) * np.exp(-np.arange(ln) / SR / 0.45); ir[0] = 0
    m = 1 << int(np.ceil(np.log2(len(x) + ln)))
    return np.fft.irfft(np.fft.rfft(x, m) * np.fft.rfft(ir, m), m)[: len(x)]

wetL, wetR = reverb(L, 1), reverb(R, 2)
L2 = L + 0.05 * wetL / np.max(np.abs(wetL)) * np.max(np.abs(L)) * 3
R2 = R + 0.05 * wetR / np.max(np.abs(wetR)) * np.max(np.abs(R)) * 3
mix = np.stack([L2, R2], 1)
fade = np.clip((DUR - np.arange(N) / SR) / 0.4, 0, 1)[:, None]
mix = np.tanh(mix * fade * 1.2)
mix *= 0.85 / np.max(np.abs(mix))
os.makedirs(os.path.join(COMP, "assets", "audio"), exist_ok=True)
with wave.open(os.path.join(COMP, "assets", "audio", "dhanteras.wav"), "wb") as w:
    w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((mix * 32767).astype(np.int16).tobytes())
print("events:", len(coins), "coins,", len(steps), "steps,", len(brands), "brand coins")
print("coin landings:", [c["t"] for c in coins][:12], "...")
